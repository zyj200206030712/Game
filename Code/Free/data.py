# 技能类，初始化技能的基本属性
class Skill:
    def __init__(self, name, value=1.0, skill_type='hp_debuff', asset_name=None, num_targets=1, duration=1, text=""):
        self.name = name  # 技能名称
        self.value = value  # *魂量得到消耗量/效果量，0~100
        self.skill_type = skill_type  # 技能类型，默认hp_debuff（伤害）
        # (hp_buff/debuff、control、defense、puppet、hundu_buff/debuff、hunliang_buff/debuff、identity_buff/debuff)
        self.asset_name = asset_name if asset_name is not None else name.lower()
        # 技能特效文件名，未指定则使用技能名称作为特效文件名
        self.num_targets = num_targets  # 技能的目标数量，默认1
        self.duration = duration  # 技能效果的持续回合数，默认1，持续性技能的每回合效果值=总消耗量÷回合数
        self.text = text  # 技能说明

