# 从角色实例字典中获取角色基础属性用于战斗模块
def get_character_stats_for_battle(Character_data):
    stats_map = {}
    for name, data in Character_data.items():
        # 战斗系统不需要处理无限属性，跳过此类角色
        if data['hp'] == '∞':
            continue
        stats_map[name] = {
            "hp": data["hp"],
            "hundu": data["hundu"],
            "hunliang": data["hunliang"],
            "skills": data.get("skills", []),
            "identity": data["identity"],
        }
    return stats_map

# 获取角色-地点映射，以及地点-角色面板显示所需的数据结构
def get_location_character_map(Character_data):
    location_map = {}
    for name, data in Character_data.items():
        for location in data.get("locations", []):
            if location not in location_map:
                location_map[location] = []

            # 提取技能名称并去重
            raw_skills = data.get("skills", [])
            display_skill_names = []
            for skill in raw_skills:
                clean_name = skill.name.replace("(武器)", "")  # 去掉名称中的 "(武器)" 字符
                if clean_name not in display_skill_names:
                    display_skill_names.append(clean_name)  # 如果去重后的名字不在列表中，则添加（保持原有顺序）
            
            skill_str = ", ".join(display_skill_names) or "无"

            # 构建角色面板场景显示所需的字典结构
            char_info_for_display = {
                "stats": {
                    "姓名": name,
                    "身份": data.get("identity", "未知"),
                    "血量": str(data.get("hp", 0)),
                    "魂度": str(data.get("hundu", 0)),
                    "魂量": str(data.get("hunliang", 0)),
                    "技能": skill_str,  # 使用处理后的字符串
                    "说明": data.get("description", "")
                }
            }
            location_map[location].append(char_info_for_display)
    return location_map


